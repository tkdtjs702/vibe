begin;

create table public.movies (
  movie_cd varchar primary key,
  movie_nm varchar not null,
  open_dt date null,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

create table public.query_periods (
  period_id bigint generated by default as identity primary key,
  period_type varchar not null check (period_type in ('daily', 'weekly', 'weekend')),
  target_date date not null,
  fetched_at timestamptz not null,
  expires_at timestamptz not null,
  source_status varchar not null check (source_status in ('success', 'empty')),
  unique (period_type, target_date)
);

create table public.period_performances (
  period_id bigint not null references public.query_periods(period_id) on delete cascade,
  movie_cd varchar not null references public.movies(movie_cd),
  rank integer not null check (rank > 0),
  sales_amt numeric(18, 0) not null check (sales_amt >= 0),
  audi_cnt bigint not null check (audi_cnt >= 0),
  sales_acc numeric(18, 0) not null check (sales_acc >= 0),
  audi_acc bigint not null check (audi_acc >= 0),
  primary key (period_id, movie_cd)
);

create index period_performances_period_id_rank_idx
  on public.period_performances (period_id, rank);

alter table public.movies enable row level security;
alter table public.query_periods enable row level security;
alter table public.period_performances enable row level security;

create or replace function public.save_box_office_period(
  p_period_type varchar,
  p_target_date date,
  p_fetched_at timestamptz,
  p_expires_at timestamptz,
  p_source_status varchar,
  p_entries jsonb
)
returns table(period_id bigint, applied boolean)
language plpgsql
security definer
set search_path = ''
as $$
declare
  v_period_id bigint;
  v_existing_fetched_at timestamptz;
begin
  if p_period_type not in ('daily', 'weekly', 'weekend')
    or p_source_status not in ('success', 'empty')
    or p_expires_at <= p_fetched_at
    or jsonb_typeof(p_entries) <> 'array'
    or (p_source_status = 'empty' and jsonb_array_length(p_entries) <> 0) then
    raise exception 'invalid box-office period input';
  end if;

  perform pg_advisory_xact_lock(hashtextextended(p_period_type || ':' || p_target_date::text, 0));

  select qp.period_id, qp.fetched_at
    into v_period_id, v_existing_fetched_at
  from public.query_periods qp
  where qp.period_type = p_period_type and qp.target_date = p_target_date
  for update;

  if found and v_existing_fetched_at > p_fetched_at then
    return query select v_period_id, false;
    return;
  end if;

  if not found then
    insert into public.query_periods (period_type, target_date, fetched_at, expires_at, source_status)
    values (p_period_type, p_target_date, p_fetched_at, p_expires_at, p_source_status)
    returning query_periods.period_id into v_period_id;
  else
    update public.query_periods
       set fetched_at = p_fetched_at,
           expires_at = p_expires_at,
           source_status = p_source_status
     where query_periods.period_id = v_period_id;
  end if;

  insert into public.movies (movie_cd, movie_nm, open_dt)
  select e.movie_cd, e.movie_nm, nullif(e.open_dt, '')::date
  from jsonb_to_recordset(p_entries) as e(
    movie_cd varchar, movie_nm varchar, open_dt varchar, rank integer,
    sales_amt numeric(18,0), audi_cnt bigint, sales_acc numeric(18,0), audi_acc bigint
  )
  on conflict (movie_cd) do update
    set movie_nm = excluded.movie_nm,
        open_dt = coalesce(excluded.open_dt, public.movies.open_dt),
        updated_at = now();

  delete from public.period_performances pp where pp.period_id = v_period_id;

  insert into public.period_performances
    (period_id, movie_cd, rank, sales_amt, audi_cnt, sales_acc, audi_acc)
  select v_period_id, e.movie_cd, e.rank, e.sales_amt, e.audi_cnt, e.sales_acc, e.audi_acc
  from jsonb_to_recordset(p_entries) as e(
    movie_cd varchar, movie_nm varchar, open_dt varchar, rank integer,
    sales_amt numeric(18,0), audi_cnt bigint, sales_acc numeric(18,0), audi_acc bigint
  );

  return query select v_period_id, true;
end;
$$;

create or replace function public.read_box_office_period(
  p_period_type varchar,
  p_target_date date
)
returns table(
  period_id bigint, period_type varchar, target_date date, fetched_at timestamptz,
  expires_at timestamptz, source_status varchar, movie_cd varchar, movie_nm varchar,
  open_dt date, rank integer, sales_amt numeric, audi_cnt bigint, sales_acc numeric, audi_acc bigint
)
language sql
security definer
set search_path = ''
stable
as $$
  select qp.period_id, qp.period_type, qp.target_date, qp.fetched_at, qp.expires_at,
         qp.source_status, m.movie_cd, m.movie_nm, m.open_dt, pp.rank, pp.sales_amt,
         pp.audi_cnt, pp.sales_acc, pp.audi_acc
  from public.query_periods qp
  left join public.period_performances pp on pp.period_id = qp.period_id
  left join public.movies m on m.movie_cd = pp.movie_cd
  where qp.period_type = p_period_type and qp.target_date = p_target_date
  order by pp.rank asc nulls last;
$$;

revoke all on function public.save_box_office_period(varchar, date, timestamptz, timestamptz, varchar, jsonb) from public, anon, authenticated;
revoke all on function public.read_box_office_period(varchar, date) from public, anon, authenticated;
grant execute on function public.save_box_office_period(varchar, date, timestamptz, timestamptz, varchar, jsonb) to service_role;
grant execute on function public.read_box_office_period(varchar, date) to service_role;

commit;
